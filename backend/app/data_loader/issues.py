"""Data issues: problems found in the supplied dataset and how the code handles them.

The dataset is never edited. Every problem is logged as a DataIssue instead, so it can be
reviewed (docs/data-issues.md), counted (health endpoint) and tested.
"""

from __future__ import annotations

from pydantic import BaseModel


class DataIssue(BaseModel, frozen=True):
    code: str        # short machine-readable kind, e.g. "text_price", "missing_rate"
    location: str    # file and row/section, e.g. "Hotels!row 8" or "content/tours/x.md"
    detail: str      # what is wrong
    handling: str    # what the code does about it


def issues_to_markdown(issues: list[DataIssue]) -> str:
    """Render issues as a Markdown table (used for docs/data-issues.md)."""

    def cell(text: str) -> str:
        return text.replace("|", "\\|").replace("\n", " ")

    lines = [
        "# Data issues",
        "",
        "Generated by `python -m app.data_loader --markdown`. The dataset is used as supplied; "
        "each issue is handled in loader code, in memory.",
        "",
        f"{len(issues)} issues.",
        "",
        "| # | Code | Location | Detail | Handling |",
        "|---|---|---|---|---|",
    ]
    for n, i in enumerate(issues, 1):
        lines.append(f"| {n} | `{i.code}` | {cell(i.location)} | {cell(i.detail)} | {cell(i.handling)} |")
    return "\n".join(lines) + "\n"
