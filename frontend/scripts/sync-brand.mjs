// Generates the brand tokens from the dataset's brand_pack.json (read-only), so colours,
// type, spacing and radii are never copied by hand.
//   node scripts/sync-brand.mjs      (npm run brand)
// Writes src/lib/brand.ts (for code) and src/app/brand.css (Tailwind v4 @theme tokens).
// The dataset folder is ../../ceylon-compass-dataset, or MIRA_DATASET_HOST_DIR if set.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const frontend = resolve(here, "..");
const dataset = process.env.MIRA_DATASET_HOST_DIR
  ? resolve(process.env.MIRA_DATASET_HOST_DIR)
  : resolve(frontend, "..", "..", "ceylon-compass-dataset");
const pack = JSON.parse(readFileSync(join(dataset, "brand", "brand_pack.json"), "utf8"));

const header = "// GENERATED by scripts/sync-brand.mjs from brand/brand_pack.json. Do not edit.\n";
const c = pack.colors;

const brand = {
  name: pack.name,
  assistantName: pack.assistant_name,
  colors: { ...c },
  accentNames: Object.keys(c.accents),
  fontFamily: pack.typography.font_family,
  scalePx: pack.typography.scale_px,
  weights: pack.typography.weights,
  spacingPx: pack.spacing_px,
  radiusPx: pack.radius_px,
  cardMaxWidthPx: pack.cards.max_width_px,
  motion: pack.motion.rule,
};
writeFileSync(
  join(frontend, "src", "lib", "brand.ts"),
  `${header}\nexport const brand = ${JSON.stringify(brand, null, 2)} as const;\n\n` +
    "export type AccentName = keyof typeof brand.colors.accents;\n",
);

const lines = [
  `/* GENERATED by scripts/sync-brand.mjs from brand/brand_pack.json. Do not edit. */`,
  "@theme {",
  `  --color-brand-black: ${c.black};`,
  `  --color-brand-white: ${c.white};`,
  `  --color-brand-orange: ${c.orange};`,
  ...Object.entries(c.accents).map(([k, v]) => `  --color-accent-${k}: ${v};`),
  `  --color-surface: ${c.surface};`,
  `  --color-ink: ${c.text};`,
  `  --color-muted: ${c.muted_text};`,
  `  --color-line: ${c.border};`,
  `  --font-brand: var(--font-inter), ${pack.typography.font_family};`,
  ...Object.entries(pack.typography.scale_px).map(([k, v]) => `  --text-brand-${k}: ${v / 16}rem;`),
  ...Object.entries(pack.radius_px).map(([k, v]) => `  --radius-${k}: ${v}px;`),
  `  --container-card: ${pack.cards.max_width_px}px;`,
  "}",
  "",
];
writeFileSync(join(frontend, "src", "app", "brand.css"), lines.join("\n"));
console.log(`Brand tokens written from ${join(dataset, "brand", "brand_pack.json")}`);
